import type { Evidence } from "../../types"
import {
  CONTEXT_INTRO,
  CONTEXT_SUFFIX,
  TEMPORARY_CONTEXT_NOTE,
  modelTokenCount,
  type ContextMaterial,
} from "./assembler"

/**
 * Ticket 61 / 04 (spec §2 L1748-1749): formats a single Evidence item as a
 * deterministic context block, mirroring the `ContextAssemblerImpl` output
 * shape — `[cite:ev_XXX] [来源: SOURCE]\nEXCERPT\n`. Used by BOTH:
 *   - `computeContextBudget` — to sum the uncompressed token count across
 *     all Evidence groups (the "would it fit without truncation?" check).
 *   - `ContextCompressorImpl` — to format each Evidence group's input block
 *     for the LLM compression call, and to generate the deterministic header
 *     (`[cite:ev_XXX] [来源: SOURCE]\n`) that wraps the LLM-produced
 *     compressed content.
 *
 * The block format is intentionally simpler than the assembler's per-parent-
 * chunk grouping (which can merge multiple child-chunk citations into one
 * header). Compression groups by Evidence ID (child chunk) — one block per
 * Evidence — so the compressed output never merges provenance across Evidence
 * identities (spec §2 L1749 acceptance criterion #2).
 */
export function formatEvidenceBlock(evidence: Evidence): string {
  return formatMaterialBlock(evidence, evidence.excerpt)
}

/**
 * PT-06:AC06 — the same deterministic block framing, but around the COMPLETE
 * chosen snippet instead of the 600-character public display preview. This is
 * the ONLY place a compressed block is framed, so a compressed context keeps
 * the byte-compatible `[cite:ID] [来源: SOURCE]\n…\n` shape the citation checker
 * and the gap-coverage rule already understand while the model gets the facts
 * that sit past character 600.
 */
export function formatMaterialBlock(evidence: Evidence, text: string): string {
  return formatCompressedBlock(evidence, text)
}

/** The deterministic header of one compressed block — `[cite:ID] [来源: SOURCE]\n`. */
export function evidenceBlockHeader(evidence: Evidence): string {
  return `[cite:${evidence.id}] [来源: ${evidence.source}]\n`
}

/**
 * PT-06:AC06 — the source identity a compressed block is allowed to claim.
 *
 * The header is generated by the compressor, never by the model, so the
 * authorized identity cannot drift. A session attachment keeps the temporary
 * reference label (Ticket 22 ATT-01): compression must not launder an
 * attachment into knowledge-base membership, and the `[cite:ID]` marker the
 * citation checker and `findUncoveredGapFacts` look for stays byte-identical.
 */
export function compressedBlockHeader(evidence: Evidence): string {
  if (evidence.origin !== "attachment") return evidenceBlockHeader(evidence)
  const name = evidence.attachmentName
    ?? (evidence.source.startsWith("附件:")
      ? evidence.source.slice("附件:".length)
      : evidence.source)
  return `[cite:${evidence.id}] [临时引用: 附件 ${name}]\n`
}

/** The ONE compressed-block shape: authorized header + body + trailing newline. */
export function formatCompressedBlock(evidence: Evidence, text: string): string {
  return `${compressedBlockHeader(evidence)}${text}\n`
}

/**
 * PT-06 / PT-07 (AC06) — the complete authorized material the compressor is
 * allowed to read for one Evidence identity.
 *
 * `Evidence.excerpt` is a 600-character DISPLAY preview for the public
 * reference list (PT-06:AC01 keeps it that way). It is NOT the material: a fact
 * after character 600 could never be summarized because the model never saw it.
 * The assembler knows the real text — the matched child snippet and the
 * per-parent window it placed in the context — and hands it over through this
 * map so the compressor receives the complete chosen snippet together with the
 * authorized source identity that already sits in the deterministic header.
 */
export interface CompressionMaterialText {
  /** The complete authorized child snippet (untruncated selected material). */
  snippet: string
  /** The per-parent candidate window the snippet sits in, when known. */
  windowText?: string
  /** The full authorized parent block, when the group was expanded to a parent. */
  parentText?: string
  /** The authorized identity triple this material belongs to (lineage, PT-06:AC06). */
  documentId: string
  chunkId: string
  parentChunkId: string
  /**
   * True when this identity's material actually reached the deterministic
   * context. An identity the budget left out is still compressible — that is
   * the point of compression — but the caller can say so honestly.
   */
  contributed: boolean
}

export type CompressionMaterialByEvidenceId = ReadonlyMap<string, CompressionMaterialText>

/**
 * Build the compressor's material map from one assembler material result:
 * every cited chunk identity, keyed by the same stable Evidence id the runners
 * cite on. Identities that only exist in the candidate list (no evidence id)
 * are not carried over — the compressor's input set is the Evidence set.
 */
export function compressionMaterialFromContextMaterial(
  material: ContextMaterial
): CompressionMaterialByEvidenceId {
  const byEvidenceId = new Map<string, CompressionMaterialText>()
  for (const source of material.sources) {
    for (const citation of source.citations) {
      if (!citation.evidenceId) continue
      byEvidenceId.set(citation.evidenceId, {
        snippet: citation.snippet,
        windowText: source.candidateText,
        parentText: source.rawText,
        documentId: citation.documentId,
        chunkId: citation.chunkId,
        parentChunkId: citation.parentChunkId,
        contributed: citation.included && source.admitted,
      })
    }
  }
  return byEvidenceId
}

/**
 * PT-06:AC06 — the body the compressor is actually shown for one Evidence:
 * the complete chosen snippet, not the public preview. Falls back to the
 * preview ONLY when the caller supplied no material (legacy loop callers).
 */
export function compressionSourceText(
  evidence: Evidence,
  material?: CompressionMaterialByEvidenceId
): string {
  const entry = material?.get(evidence.id)
  if (!entry) return evidence.excerpt
  return entry.snippet.length > 0 ? entry.snippet : evidence.excerpt
}

export interface MaterialBudgetOptions {
  /** Same default as `ContextBudgetOptions.maxContextTokens` (`6_000`). */
  maxContextTokens?: number
  countTokens?: (text: string) => number
}

export interface MaterialBudgetBreakdown {
  /** COUNT 1 — the complete authorized parent blocks. */
  rawTokens: number
  /** COUNT 2 — the per-parent candidate windows (material text only). */
  candidateTokens: number
  /** COUNT 2 with every fixed text counted: INTRO/attachment note/SUFFIX + headers/citations. */
  candidateContextTokens: number
  /** COUNT 3 — the exact deterministic context the assembler produced. */
  finalTokens: number
  /** The budget the decision was made against (unchanged default 6000). */
  maxContextTokens: number
  /**
   * PT-06:AC03 — `true` only when the REAL candidate material exceeds the
   * budget, so the caller attempts compression (or records a refusal reason).
   * `false` means the deterministic material already fits: no extra model call.
   */
  overBudget: boolean
  /** Whether the final deterministic context is inside the budget (it must be). */
  finalWithinBudget: boolean
  /** Fixed framing (INTRO + temporary-attachment note + SUFFIX). */
  framingTokens: number
  /** Number of groups the budget walk could not admit. */
  omittedSourceCount: number
  evidenceIds: string[]
}

/**
 * PT-06:AC02/AC03 — decide compression from the assembler's REAL counts.
 *
 * This replaces the preview-sum heuristic of `computeContextBudget` for every
 * material-backed caller: the candidate text after the per-parent window (plus
 * all fixed framing) is compared against the same `maxContextTokens`, so a
 * 30,000-token parent whose 600-character preview looked cheap is now seen for
 * what it is, and a genuinely small material still costs no model call.
 */
export function computeMaterialBudget(
  material: ContextMaterial,
  options: MaterialBudgetOptions = {}
): MaterialBudgetBreakdown {
  const maxContextTokens = options.maxContextTokens ?? 6_000
  const countTokens = options.countTokens ?? modelTokenCount

  const intro = material.sources.some((source) => source.temporary)
    ? `${CONTEXT_INTRO}${TEMPORARY_CONTEXT_NOTE}`
    : CONTEXT_INTRO
  const framingTokens = countTokens(`${intro}${CONTEXT_SUFFIX}`)
  let framingCandidateTokens = 0
  let candidateTokens = 0
  let rawTokens = 0
  const evidenceIds: string[] = []
  for (const source of material.sources) {
    // The candidate text is the window at the per-parent cap; the header is the
    // one the assembler reserved budget for, so the measurement matches the
    // framing the deterministic output actually pays.
    candidateTokens += countTokens(source.candidateText)
    framingCandidateTokens += countTokens(
      `${source.headerText}${source.candidateText}\n`
    )
    rawTokens += countTokens(source.rawText)
    for (const citation of source.citations) {
      if (citation.evidenceId) evidenceIds.push(citation.evidenceId)
    }
  }
  const candidateContextTokens = framingTokens + framingCandidateTokens
  const finalTokens = countTokens(material.context)

  return {
    rawTokens,
    candidateTokens,
    candidateContextTokens,
    finalTokens,
    maxContextTokens,
    overBudget: candidateContextTokens > maxContextTokens,
    finalWithinBudget: finalTokens <= maxContextTokens,
    framingTokens,
    omittedSourceCount: material.sources.filter((source) => !source.admitted).length,
    evidenceIds,
  }
}

export interface ContextBudgetOptions {
  /**
   * Maximum context token budget. Defaults to `6_000` — the same default as
   * `ContextAssemblerImpl.maxContextTokens`.
   */
  maxContextTokens?: number
  /**
   * Token-counting function. Defaults to `modelTokenCount` (exported from
   * `assembler.ts`) — the same function used by the deterministic assembler
   * for budget enforcement. Chinese text → UTF-8 byte length; ASCII text →
   * llamaindex tokenizer token count.
   */
  countTokens?: (text: string) => number
}

export interface ContextBudgetBreakdown {
  /**
   * Total token count of the PREVIEW framing — INTRO + one
   * `formatEvidenceBlock` per Evidence (600-char display excerpts, no
   * truncation/windowing) + SUFFIX.
   *
   * PT-06 (F4): this is a LOWER bound on what the generator really receives,
   * never an upper bound. `Evidence.excerpt` is a public display preview and an
   * assembler group can carry a parent window far larger than it, so this value
   * MUST NOT be used to decide compression for a material-backed run — see
   * `computeMaterialBudget`. Kept for the legacy string/preview callers
   * (`ContextCompressor.compress`, the complex loop observation adapter).
   */
  uncompressedTokens: number
  /**
   * The maximum context token budget. Same value as
   * `ContextAssemblerImpl.maxContextTokens` (default `6_000`).
   */
  maxContextTokens: number
  /**
   * Whether the PREVIEW framing exceeds the budget. `true` is a proof that the
   * real material does too; `false` proves nothing about the material, so a
   * material-backed caller must decide with `computeMaterialBudget` instead.
   */
  overBudget: boolean
  /**
   * All Evidence IDs in the input array, in insertion order. Used by the
   * compressor to validate that the compressed output does not create new
   * citation identities or retain an unknown Evidence ID (spec §2 L1749
   * acceptance criterion #4).
   */
  evidenceIds: string[]
}

/**
 * Ticket 61 / 04 (spec §2 L1748): computes the PREVIEW framing token count for
 * a set of Evidence and determines whether that preview sum exceeds a budget.
 *
 * PT-06 (F4) — the old claim that this is an UPPER bound on the assembler's
 * output was wrong and is no longer made. `Evidence.excerpt` is a 600-character
 * public display preview; an assembler group carries the per-parent window,
 * which is routinely LARGER than the preview (audited: 30,000 tokens of parent
 * material behind 3,854 tokens of preview). So:
 *   - `overBudget === true`  → proof that the real material also exceeds the
 *     budget (the preview is a lower bound), so compression may be attempted.
 *   - `overBudget === false` → NO information about the real material. A
 *     material-backed caller MUST decide with `computeMaterialBudget` instead,
 *     or it will silently skip compression for oversized material.
 *
 * It stays exported for the legacy preview callers (the complex-loop observation
 * compressor adapter, `ContextCompressor.compress` without material) so their
 * behavior is unchanged until those callers are migrated.
 */
export function computeContextBudget(
  evidence: Evidence[],
  options: ContextBudgetOptions = {}
): ContextBudgetBreakdown {
  const maxContextTokens = options.maxContextTokens ?? 6_000
  const countTokens = options.countTokens ?? modelTokenCount
  const overhead = countTokens(CONTEXT_INTRO + CONTEXT_SUFFIX)
  const blocksTokens = evidence.reduce(
    (sum, ev) => sum + countTokens(formatEvidenceBlock(ev)),
    0
  )
  const uncompressedTokens = overhead + blocksTokens
  return {
    uncompressedTokens,
    maxContextTokens,
    overBudget: uncompressedTokens > maxContextTokens,
    evidenceIds: evidence.map((ev) => ev.id),
  }
}
